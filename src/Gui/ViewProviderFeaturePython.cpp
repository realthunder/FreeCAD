static QPixmap getPixmapFromPython(Py::Object pyobj)
{
    if(pyobj.isString()) {
        std::string content = Py::String(pyobj).as_std_string("utf-8");
        QPixmap icon = BitmapFactory().pixmap(content.c_str(), true);
        if (!icon.isNull())
            return icon;

        // Check if the passed string is a filename, otherwise treat as xpm data
        QFileInfo fi(QString::fromUtf8(content.c_str()));
        if (fi.isFile() && fi.exists()) {
            icon.load(fi.absoluteFilePath());
        } else {
            QByteArray ary;
            int strlen = (int)content.size();
            ary.resize(strlen);
            for (int j=0; j<strlen; j++)
                ary[j]=content[j];
            // Make sure to remove crap around the XPM data
            QList<QByteArray> lines = ary.split('\n');
            QByteArray buffer;
            buffer.reserve(ary.size()+lines.size());
            for (QList<QByteArray>::iterator it = lines.begin(); it != lines.end(); ++it) {
                QByteArray trim = it->trimmed();
                if (!trim.isEmpty()) {
                    buffer.append(trim);
                    buffer.append('\n');
                }
            }
            icon.loadFromData(buffer, "XPM");
        }
        if (!icon.isNull()) {
            return icon;
        }
    } else {
        PythonWrapper wrap;
        wrap.loadGuiModule();
        QPixmap *px = wrap.toQPixmap(pyobj.ptr());
        if(px)
            return *px;
    }
    return QPixmap();
}

/** Wrap a Coin pointer for pivy
 *
 * The conversion throws a Base::Exception rather than a Python error, and every
 * hook that uses it reported that and carried on rather than letting it escape
 * into Coin. Keep that here, where the argument is built.
 */
static bool swigPointer(Py::Object &out, const char *type, void *ptr, int own)
{
    try {
        out = Py::asObject(Base::Interpreter().createSWIGPointerObj(
                    "pivy.coin", type, ptr, own));
        return true;
    }
    catch (const Base::Exception& e) {
        e.ReportException();
        return false;
    }
}

QIcon ViewProviderFeaturePythonImp::getIcon() const
{
    QIcon icon;
    callHook(HookGetIcon, [&](const Py::Object& ret) {
        if (ret.isNone())
            return true;

        std::string _type;
        const char *type = nullptr;
        if (object && object->getObject()) {
            auto prop = Base::freecad_dynamic_cast<App::PropertyPythonObject>(
                    object->getObject()->getPropertyByName("Proxy"));
            if (prop) {
                try {
                    auto proxy = prop->getValue();
                    if(!proxy.isNone() && !proxy.isString() && !proxy.isNumeric()) {
                        if (proxy.hasAttr("__class__")) {
                            _type = proxy.getAttr("__class__").as_string();
                            type = _type.c_str();
                        } else
                            type = proxy.ptr()->ob_type->tp_name;
                    }
                } catch (Py::Exception &) {
                    Base::PyException e;
                    e.ReportException();
                }
            }
        }
        BitmapCacheContext ctx(type);

        QPixmap px = getPixmapFromPython(ret);
        if (!px.isNull()) {
            icon = px;
            return true;
        }

        PythonWrapper wrap;
        wrap.loadGuiModule();
        wrap.loadWidgetsModule();
        QIcon *picon = wrap.toQIcon(ret.ptr());
        if(picon)
            icon = *picon;
        return true;
    });
    return icon;
}

void ViewProviderFeaturePythonImp::getExtraIcons(
        std::vector<std::pair<QByteArray, QPixmap> > &icons) const
{
    if (!canCallHook(HookGetExtraIcons))
        return;

    Base::PyGILStateLocker lock;
    Py::List list;
    PythonWrapper wrap;
    wrap.loadGuiModule();
    for (auto &v : icons)
        list.append(Py::TupleN(Py::String(v.first.constData()),
                               wrap.fromQPixmap(&v.second)));

    callHook(HookGetExtraIcons, [&icons](const Py::Object& ret) {
        if (ret.isNone())
            return true;

        std::vector<std::pair<QByteArray, QPixmap> >res;
        if (ret.isSequence() && !ret.isString()) {
            Py::Sequence seq(ret);
            if (seq.size() == 2) {
                Py::Object first(seq[0].ptr());
                if (first.isString()) {
                    QPixmap px = getPixmapFromPython(Py::Object(seq[1].ptr()));
                    if (!px.isNull())
                        res.emplace_back(first.as_string().c_str(), px);
                    // note this leaves icons untouched, as it always has
                    return true;
                }
            }
            for (int i=0, c=seq.size(); i<c; ++i) {
                std::string tag;
                QPixmap px;
                if (PySequence_Check(seq[i].ptr())) {
                    Py::Sequence s(seq[i].ptr());
                    if (s.size() == 2) {
                        Py::Object first(s[0].ptr());
                        if (first.isString()) {
                            tag = first.as_string();
                            px = getPixmapFromPython(Py::Object(s[1]));
                        }
                    }
                } else
                    px = getPixmapFromPython(Py::Object(seq[i]));
                if (!px.isNull())
                    res.emplace_back(tag.c_str(), px);
            }
        }
        else {
            QPixmap px = getPixmapFromPython(ret);
            if (!px.isNull())
                res.emplace_back(QByteArray(), px);
        }
        icons = std::move(res);
        return true;
    }, Py::Object(list));
}

bool ViewProviderFeaturePythonImp::claimChildren(std::vector<App::DocumentObject*> &children) const
{
    auto state = callHook(HookClaimChildren, [&children](const Py::Object& res) {
        Py::Sequence list(res);
        for (Py::Sequence::iterator it = list.begin(); it != list.end(); ++it) {
            Py::Object item(*it);
            if (PyObject_TypeCheck(item.ptr(), &(App::DocumentObjectPy::Type))) {
                App::DocumentObject* obj =
                    static_cast<App::DocumentObjectPy*>(item.ptr())->getDocumentObjectPtr();
                children.push_back(obj);
            }
        }
        return true;
    });
    if (state == PyHookState::Failed)
        return true;
    return state == PyHookState::Handled;
}

