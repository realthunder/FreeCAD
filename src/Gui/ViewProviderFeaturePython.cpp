ViewProviderFeaturePythonImp::ValueT
ViewProviderFeaturePythonImp::reorderObjects(
        const std::vector<App::DocumentObject *> &objs, App::DocumentObject *before)
{
    if (!canCallHook(HookReorderObjects))
        return NotImplemented;

    Base::PyGILStateLocker lock;
    Py::List list;
    for (auto obj : objs) {
        if (obj && obj->getNameInDocument())
            list.append(Py::asObject(obj->getPyObject()));
    }

    ValueT ret = NotImplemented;
    if (callHook(HookReorderObjects, App::pyHookDecodeValueT(ret), Py::Object(list), before)
            == PyHookState::Failed)
        return Rejected;
    return ret;
}

