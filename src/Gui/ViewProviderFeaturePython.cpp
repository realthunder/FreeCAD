bool ViewProviderFeaturePythonImp::getElement(const SoDetail *det, std::string &res) const
{
    if (!canCallHook(HookGetElement))
        return false;

    Base::PyGILStateLocker lock;
    Py::Object pivy;
    // Note: As there is no ref'counting mechanism for the SoDetail class we must
    // pass '0' as the last parameter so that the Python object does not 'own'
    // the detail object.
    if (!swigPointer(pivy, "SoDetail *",
                     const_cast<void*>(static_cast<const void*>(det)), 0))
        return true;

    auto state = callHook(HookGetElement, [&res](const Py::Object& ret) {
        Py::String name(ret);
        res = name;
        return true;
    }, pivy);
    if (state == PyHookState::Failed)
        return true;
    return state == PyHookState::Handled;
}

ViewProviderFeaturePythonImp::ValueT
ViewProviderFeaturePythonImp::getElementPicked(const SoPickedPoint *pp, std::string &subname) const
{
    if (!canCallHook(HookGetElementPicked))
        return NotImplemented;

    Base::PyGILStateLocker lock;
    Py::Object pivy;
    if (!swigPointer(pivy, "SoPickedPoint *",
                     const_cast<void*>(static_cast<const void*>(pp)), 0))
        return Rejected;

    ValueT ret = Rejected;
    auto state = callHook(HookGetElementPicked, [&](const Py::Object& res) {
        if (!res.isString()) {
            ret = Rejected;
            return true;
        }
        subname = res.as_string();
        ret = Accepted;
        return true;
    }, pivy);
    if (state == PyHookState::Failed)
        return Rejected;
    if (state == PyHookState::NotHandled)
        return NotImplemented;
    return ret;
}

bool ViewProviderFeaturePythonImp::getDetail(const char* name, SoDetail *&det) const
{
    auto state = callHook(HookGetDetail, [&det](const Py::Object& pydet) {
        void* ptr = nullptr;
        Base::Interpreter().convertSWIGPointerObj("pivy.coin", "SoDetail *",
                                                  pydet.ptr(), &ptr, 0);
        auto detail = static_cast<SoDetail*>(ptr);
        det = detail ? detail->copy() : nullptr;
        return true;
    }, name);
    if (state == PyHookState::Failed)
        return true;
    return state == PyHookState::Handled;
}

ViewProviderFeaturePythonImp::ValueT ViewProviderFeaturePythonImp::getDetailPath(
        const char* name, SoFullPath *path, bool append, SoDetail *&det) const
{
    if (!canCallHook(HookGetDetailPath))
        return NotImplemented;

    Base::PyGILStateLocker lock;
    auto length = path->getLength();

    Py::Object pivy;
    if (!swigPointer(pivy, "SoFullPath *", static_cast<void*>(path), 1)) {
        path->truncate(length);
        return Rejected;
    }
    path->ref();

    ValueT ret = Rejected;
    bool truncate = true;
    auto state = callHook(HookGetDetailPath, [&](const Py::Object& pyDet) {
        if (!pyDet.isTrue()) {
            ret = Rejected;
            truncate = false;
            return true;
        }
        if (pyDet.isBoolean()) {
            ret = Accepted;
            truncate = false;
            return true;
        }
        void* ptr = nullptr;
        Base::Interpreter().convertSWIGPointerObj("pivy.coin", "SoDetail *",
                                                  pyDet.ptr(), &ptr, 0);
        auto detail = static_cast<SoDetail*>(ptr);
        det = detail ? detail->copy() : nullptr;
        if (det) {
            ret = Accepted;
            truncate = false;
            return true;
        }
        delete det;
        return true;
    }, name, pivy, append);

    if (state == PyHookState::NotHandled)
        return NotImplemented;
    if (truncate)
        path->truncate(length);
    return state == PyHookState::Failed ? Rejected : ret;
}


